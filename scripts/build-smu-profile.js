#!/usr/bin/env node
/* ---------------------------------------------------------------------------
   Builds the CSV export and the inventory from the canonical data file.

     data/smu-houston-profile.js  (canonical, edited by hand)
       -> data/smu-houston-profile.csv
       -> docs/smu-houston-profile-inventory.md

   Usage:
     node scripts/build-smu-profile.js           write both files
     node scripts/build-smu-profile.js --check   exit 1 if either is stale

   No dependencies. Output uses CRLF line endings, like the rest of the repo.
--------------------------------------------------------------------------- */
'use strict';
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.resolve(__dirname, '..');
const DATA = path.join(ROOT, 'data', 'smu-houston-profile.js');
const CSV = path.join(ROOT, 'data', 'smu-houston-profile.csv');
const INVENTORY = path.join(ROOT, 'docs', 'smu-houston-profile-inventory.md');

function loadData(file = DATA) {
  const ctx = { window: {} };
  vm.runInNewContext(fs.readFileSync(file, 'utf8'), ctx, { filename: file });
  const D = ctx.window.SMU_HOUSTON_PROFILE;
  if (!D) throw new Error('data file did not define window.SMU_HOUSTON_PROFILE');
  return D;
}

const STATUS_TEXT = {
  'reported': 'Reported',
  'not-labeled': 'Not labeled in the report',
  'not-shown': 'Not shown in the report'
};
const GEO_TEXT = { houston: 'Houston', national: 'National benchmark' };

function indexes(D) {
  const view = Object.fromEntries(D.views.map(v => [v.id, v]));
  const metric = Object.fromEntries(D.metrics.map(m => [m.id, m]));
  const section = Object.fromEntries(D.sections.map(s => [s.id, s]));
  const rowNote = {};
  D.rowNotes.forEach(n => { rowNote[`${n.metric}|${n.view}|${n.geo}`] = n.note; });
  /* group size per view and geography, from the cohort records */
  const n = {};
  D.values.forEach(r => {
    if (r.metric === 'orgs_total') n[`overall|${r.geo}`] = r;
    if (r.metric === 'orgs_by_discipline_count' || r.metric === 'orgs_by_budget_count') n[`${r.component}|${r.geo}`] = r;
  });
  return { view, metric, section, rowNote, n };
}

/* ------------------------------------------------------------------ CSV --- */
function csvCell(v) {
  if (v === null || v === undefined) return '';
  const s = String(v);
  return /[",\r\n]/.test(s) ? '"' + s.replace(/"/g, '""') + '"' : s;
}

function buildCSV(D) {
  const I = indexes(D);
  const cols = ['metric', 'metric_name', 'section', 'view', 'view_label', 'view_mode', 'geography',
    'component', 'component_label', 'value', 'unit', 'display', 'status', 'period', 'pdf_page',
    'group_n', 'note', 'row_note'];
  const rows = [cols];
  D.values.forEach(r => {
    const m = I.metric[r.metric];
    const v = I.view[r.view];
    const g = I.n[`${r.view}|${r.geo}`];
    rows.push([
      r.metric, m.name, I.section[m.section].name, r.view, v.label, v.mode, GEO_TEXT[r.geo],
      r.component || '', r.component ? D.componentLabels[r.component] : '',
      r.value, D.units[m.unit], r.display, STATUS_TEXT[r.status], r.period, r.page,
      g ? g.value : '', r.note || '', I.rowNote[`${r.metric}|${r.view}|${r.geo}`] || ''
    ]);
  });
  return rows.map(row => row.map(csvCell).join(',')).join('\r\n') + '\r\n';
}

/* ------------------------------------------------------------ inventory --- */
function mdCell(s) { return String(s === null || s === undefined ? '' : s).replace(/\|/g, '\\|'); }
function table(head, rows) {
  return [
    '| ' + head.join(' | ') + ' |',
    '|' + head.map(() => '---').join('|') + '|',
    ...rows.map(r => '| ' + r.map(mdCell).join(' | ') + ' |')
  ].join('\n');
}

function buildInventory(D) {
  const I = indexes(D);
  const S = D.source;
  const out = [];
  out.push('# Inventory: SMU DataArts Houston FY25 profile', '');
  out.push('Generated by `node scripts/build-smu-profile.js` from `data/smu-houston-profile.js`, the canonical source. Do not edit this file by hand; edit the data file and rebuild.', '');
  out.push(`**Source.** ${S.author}, *${S.title}*. ${S.creditLine} Publication year ${S.publicationYear || 'pending'}${S.publicationDate ? `, published ${S.publicationDate}` : ''}. File: \`${S.fileName}\`, ${S.pageCount} pages, generated ${S.fileGenerated}. Presented by ${S.presentedBy} in an interactive format.`, '');
  out.push(`**Houston cohort.** ${S.houston.n.toLocaleString('en-US')} organizations: ${S.houston.description}. The report describes the Houston data as "${S.houston.reportDescription}". A selected group, not a census.`, '');
  out.push(`**National benchmark.** ${S.national.n.toLocaleString('en-US')} organizations: ${S.national.benchmark} (${S.national.description}). Not representative of all U.S. nonprofit arts organizations.`, '');
  out.push(`**Period.** ${S.period} for every statistic, Houston and national.`, '');

  out.push('## How values were extracted', '');
  (S.extractionNotes || []).forEach(t => out.push(`- ${t}`));
  out.push('');

  out.push('## Conventions', '');
  out.push(
    '- **n.** The group size published in the cohort profile. The report does not publish per-metric n.',
    `- **PDF page.** PDF page index.${S.printedPageNumbers ? '' : ' The report prints no page numbers.'}`,
    '- **Value and display.** Value is the published number in the metric\'s unit, at published precision; display is the string exactly as printed.',
    '- **Status.** "Reported" values are printed in the report. "Not labeled in the report" means a segment is drawn with no printed value; it is never back-solved. "Not shown in the report" means no segment is drawn for that category in that row; it is not recorded as 0%. No derived figures are stored.',
    '- **Averages.** Every "average" metric is a mean per organization; the report gives no medians.',
    ''
  );

  out.push('## Coverage by view', '');
  const modes = ['overall', 'discipline', 'budget'];
  out.push(table(['Metric', 'Overall', 'Disciplines', 'Budget bands', 'Pages'],
    D.metrics.map(m => [m.name, ...modes.map(md => m.coverage.includes(md) ? 'Yes' : (md !== 'overall' && m.coverage.length === 1 ? 'Supplies group n' : '**Not reported**')), m.pages.join(', ')])));
  out.push('', 'The report provides no discipline x budget intersections.', '');

  out.push('## Group sizes', '');
  const shareMetric = { discipline: 'orgs_by_discipline_share', budget: 'orgs_by_budget_share' };
  const share = (v, g) => {
    const r = D.values.find(x => x.metric === shareMetric[I.view[v].mode] && x.component === v && x.geo === g);
    return r ? ` (${r.display})` : '';
  };
  out.push(table(['View', 'Houston n', 'National n', 'PDF page'], D.views.map(v => {
    const h = I.n[`${v.id}|houston`], nn = I.n[`${v.id}|national`];
    return [v.label + (v.reportLabel !== v.label && v.mode !== 'overall' ? ` (report label: "${v.reportLabel}")` : ''),
      h.display + share(v.id, 'houston'), nn.display + share(v.id, 'national'), h.page];
  })), '');

  out.push('## Composition rows that need a note', '');
  out.push(table(['Metric', 'View', 'Geography', 'Note'],
    D.rowNotes.map(n => [I.metric[n.metric].name, I.view[n.view].label, GEO_TEXT[n.geo], n.note])), '');

  out.push('## Metric definitions', '');
  out.push(table(['Metric', 'Unit', 'Pages', 'Definition'],
    D.metrics.map(m => [m.name, D.units[m.unit], m.pages.join(', '), m.definition])), '');

  out.push(`## Every statistic (${D.values.length} rows)`, '');
  out.push(table(['#', 'Section', 'Metric', 'View', 'Component', 'Geography', 'n', 'Value', 'Unit', 'Display (as published)', 'Status', 'Period', 'PDF page', 'Notes'],
    D.values.map((r, i) => {
      const m = I.metric[r.metric];
      const g = I.n[`${r.view}|${r.geo}`];
      return [i + 1, I.section[m.section].name, m.name, I.view[r.view].label,
        r.component ? D.componentLabels[r.component] : '', GEO_TEXT[r.geo], g ? g.display : '',
        r.value === null ? '' : r.value, D.units[m.unit], r.display === null ? '' : '`' + r.display + '`',
        STATUS_TEXT[r.status], r.period, r.page, r.note || ''];
    })), '');
  return out.join('\n').replace(/\n/g, '\r\n');
}

function main() {
  const check = process.argv.includes('--check');
  const D = loadData();
  const outputs = [[CSV, buildCSV(D)], [INVENTORY, buildInventory(D)]];
  let stale = 0;
  for (const [file, text] of outputs) {
    const rel = path.relative(ROOT, file);
    if (check) {
      const cur = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
      if (cur !== text) { stale++; console.error(`stale: ${rel} (run node scripts/build-smu-profile.js)`); }
      else console.log(`up to date: ${rel}`);
    } else {
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, text);
      console.log(`wrote ${rel}`);
    }
  }
  if (stale) process.exit(1);
}

if (require.main === module) main();
module.exports = { loadData, buildCSV, buildInventory, DATA, CSV, INVENTORY };
